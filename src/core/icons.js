/**
 * Get category icon SVG
 */
export function getCategoryIconSvg(catId) {
  switch (catId) {
    case 'all': return ICONS.all;
    case 'images': return ICONS.image;
    case 'documents': return ICONS.document;
    case 'video': return ICONS.video;
    case 'audio': return ICONS.audio;
    case '3d': return ICONS.box3d;
    case 'data': return ICONS.data;
    case 'code': return ICONS.code;
    default: return ICONS.zap;
  }
}

/**
 * Get tool icon SVG based on tool metadata
 */
export function getToolIconSvg(tool) {
  if (!tool) return ICONS.zap;
  const id = tool.id || '';
  const cat = tool.category || '';

  if (id.includes('latex') || id.includes('tex')) {
    return ICONS.latex;
  }
  if (id.includes('pdf')) {
    return ICONS.pdf;
  }
  if (id.includes('compress') || id.includes('shrink')) {
    return ICONS.compress;
  }
  if (id.includes('crop') || id.includes('resize')) {
    return ICONS.crop;
  }
  if (id.includes('effects') || id.includes('watermark')) {
    return ICONS.droplet;
  }

  switch (cat) {
    case 'images': return ICONS.image;
    case 'documents': return ICONS.document;
    case 'video': return ICONS.video;
    case 'audio': return ICONS.audio;
    case '3d': return ICONS.box3d;
    case 'data': return ICONS.data;
    case 'code': return ICONS.code;
    default: return ICONS.zap;
  }
}

/**
 * Get file type SVG icon for uploads / thumbnails
 */
export function getFileThumbIconSvg(filename = '', mimeType = '') {
  const name = filename.toLowerCase();
  if (mimeType.startsWith('image/') || /\.(png|jpe?g|webp|gif|bmp|svg|avif|ico|tiff)$/i.test(name)) {
    return ICONS.image;
  }
  if (/\.(pdf)$/i.test(name)) {
    return ICONS.pdf;
  }
  if (/\.(tex|latex)$/i.test(name)) {
    return ICONS.latex;
  }
  if (/\.(docx?|pptx?|xlsx?|odt|rtf|txt|md|markdown)$/i.test(name)) {
    if (/\.(xlsx?|csv)$/i.test(name)) return ICONS.data;
    return ICONS.document;
  }
  if (mimeType.startsWith('audio/') || /\.(mp3|wav|ogg|flac|aac|m4a)$/i.test(name)) {
    return ICONS.audio;
  }
  if (mimeType.startsWith('video/') || /\.(mp4|webm|mov|mkv|avi)$/i.test(name)) {
    return ICONS.video;
  }
  if (/\.(obj|stl|fbx|gltf|glb)$/i.test(name)) {
    return ICONS.box3d;
  }
  if (/\.(json|csv|xml|yaml|yml|sql)$/i.test(name)) {
    return ICONS.data;
  }
  if (/\.(js|ts|jsx|tsx|html|css|py|sh)$/i.test(name)) {
    return ICONS.code;
  }
  return ICONS.document;
}
